/**
 * Calculate tart pricing based on quantity
 */
export function calculateTartPrice(categoryId, quantity) {
  const category = PRODUCTS.find(p => p.id === categoryId);
  if (!category?.pricing?.tiers) return null;
  
  const { tiers, minimum } = category.pricing;
  if (quantity < minimum) return { error: `Minimum order is ${minimum} pieces.` };
  
  for (let i = tiers.length - 1; i >= 0; i--) {
    const tier = tiers[i];
    // Check if quantity meets this tier's minimum
    // Parse the minimum from the label
    const tierMin = i === 0 ? minimum : parseInt(tiers[i].label.split(' ')[0]);
    if (quantity >= tierMin) {
      return {
        pricePerUnit: tier.pricePerUnit,
        total: tier.pricePerUnit * quantity,
        display: `${quantity} × ${tier.display} = RM${(tier.pricePerUnit * quantity).toFixed(2)}`,
      };
    }
  }
  return null;
}
